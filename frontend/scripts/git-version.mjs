import { execSync } from 'child_process';
import { writeFileSync, mkdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outDir = join(__dirname, '..', 'src', 'environments');
const outFile = join(outDir, 'version.ts');
mkdirSync(outDir, { recursive: true });

function run(cmd) {
  try {
    return execSync(cmd, { encoding: 'utf8' }).trim();
  } catch {
    return '';
  }
}

const commitCount = run('git rev-list --count HEAD');
const shortHash  = run('git rev-parse --short HEAD');

const label = commitCount || process.env.VERSION || 'dev';

writeFileSync(outFile, `// Auto-generated by scripts/git-version.mjs — do not edit
export const appVersion = 'v${label}';\n`);
